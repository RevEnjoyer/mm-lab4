"""
Модуль фильтров для фоторедактора.

Лабораторная работа 3.1, вариант 1: обязателен только фильтр
"Оттенки серого". Вынесен в отдельный модуль (а не оставлен методом
класса PhotoEditor), чтобы саму логику обработки изображений можно
было использовать и тестировать отдельно от GUI.
"""

import cv2


def apply_grayscale(image):
    """
    Преобразует цветное изображение в оттенки серого.

    :param image: изображение в формате BGR (NumPy-массив из cv2.imread)
    :return: изображение в оттенках серого, приведённое обратно
             к трёхканальному BGR-формату
    """
    # cv2.COLOR_BGR2GRAY сворачивает 3 канала (B, G, R) в один канал
    # яркости, вычисленный по формуле 0.299*R + 0.587*G + 0.114*B.
    # Коэффициенты неравные (а не простое усреднение трёх каналов)
    # потому, что человеческий глаз наиболее чувствителен к зелёному
    # цвету и менее всего - к синему; такая формула даёт результат,
    # визуально более похожий на то, как яркость воспринимает глаз.
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Результат cv2.cvtColor(..., COLOR_BGR2GRAY) - ОДНОканальный массив
    # (только яркость, без цветовых каналов). Остальной код приложения
    # (отображение, сохранение) унифицированно работает с трёхканальными
    # BGR-изображениями, поэтому конвертируем обратно в BGR: все три
    # канала получат одинаковое значение, изображение останется
    # визуально чёрно-белым, но технически будет трёхканальным, как и
    # любое другое изображение в программе - не нужно отдельной ветки
    # кода для одноканального случая.
    return cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
